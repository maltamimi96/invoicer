#!/usr/bin/env node
/**
 * Compiles the SEO agent prompts (src/lib/seo/agents/*.md) into a bundled TS
 * module so the job engine can read them reliably at runtime on Vercel
 * (loose .md files aren't guaranteed to be traced into serverless functions).
 *
 * The .md files remain the editable source of truth. After editing one, run:
 *   node scripts/build-agent-prompts.mjs
 * and commit the regenerated src/lib/seo/agent-prompts.generated.ts.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = "src/lib/seo/agents";
const OUT = "src/lib/seo/agent-prompts.generated.ts";

/** Strip YAML frontmatter (--- … ---) and return the body prompt. */
function stripFrontmatter(md) {
  if (md.startsWith("---")) {
    const end = md.indexOf("\n---", 3);
    if (end !== -1) return md.slice(md.indexOf("\n", end + 1) + 1).trimStart();
  }
  return md;
}

const files = readdirSync(DIR).filter((f) => f.endsWith(".md")).sort();
const entries = files.map((f) => {
  const id = f.replace(/\.md$/, "");
  const body = stripFrontmatter(readFileSync(join(DIR, f), "utf8")).trimEnd();
  return [id, body];
});

const banner =
  "// AUTO-GENERATED by scripts/build-agent-prompts.mjs — do not edit by hand.\n" +
  "// Source of truth: src/lib/seo/agents/*.md. Regenerate after editing a prompt.\n\n";

const body =
  "export const AGENT_PROMPTS: Record<string, string> = {\n" +
  entries
    .map(([id, prompt]) => `  ${JSON.stringify(id)}: ${JSON.stringify(prompt)},`)
    .join("\n") +
  "\n};\n";

writeFileSync(OUT, banner + body);
console.log(`Wrote ${OUT} — ${entries.length} prompts (${entries.map((e) => e[0]).join(", ")})`);
