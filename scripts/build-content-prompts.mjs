#!/usr/bin/env node
/**
 * Compiles the Content Studio agent prompts (src/lib/content/agents/*.md) into
 * a bundled TS module, so the engine can read them at runtime on Vercel —
 * loose .md files aren't guaranteed to be traced into serverless functions.
 *
 * You do NOT need to run this by hand: it's wired to `prebuild` in package.json
 * and asserted by a test. That's deliberate. The SEO equivalent
 * (build-agent-prompts.mjs) is manual, so editing a prompt and forgetting the
 * script silently ships the OLD prompt to production with nothing to catch it.
 *
 * The .md files are pure prompt — no YAML frontmatter. All metadata (name,
 * tools, model, produces/consumes) lives in src/lib/content/pipeline.ts. One
 * fact, one home: the SEO prompts declare `tools:` in frontmatter AND in
 * pipeline.ts, and the two have already drifted apart.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const DIR = "src/lib/content/agents";
const OUT = "src/lib/content/agent-prompts.generated.ts";

export function buildPrompts() {
  const files = readdirSync(DIR).filter((f) => f.endsWith(".md")).sort();

  const entries = files.map((f) => {
    const id = f.replace(/\.md$/, "");
    const body = readFileSync(join(DIR, f), "utf8");

    // Frontmatter here would mean metadata lives in two places. Fail loudly
    // rather than silently discard it, which is how SEO's drifted.
    if (body.startsWith("---")) {
      throw new Error(
        `${f} starts with YAML frontmatter. Content prompts are pure prompt text — ` +
          `put metadata in src/lib/content/pipeline.ts instead.`
      );
    }
    if (!body.trim()) throw new Error(`${f} is empty.`);

    return [id, body.trim()];
  });

  const banner =
    "// AUTO-GENERATED by scripts/build-content-prompts.mjs — do not edit by hand.\n" +
    "// Source of truth: src/lib/content/agents/*.md.\n" +
    "// Regenerated automatically by `npm run build` (prebuild) and asserted by a test.\n\n";

  const body =
    "export const CONTENT_PROMPTS: Record<string, string> = {\n" +
    entries.map(([id, p]) => `  ${JSON.stringify(id)}: ${JSON.stringify(p)},`).join("\n") +
    "\n};\n";

  return { source: banner + body, ids: entries.map((e) => e[0]) };
}

// Only write when run directly — the test imports buildPrompts() to diff.
// pathToFileURL, not string concat: on Windows argv[1] is `C:\...` and
// import.meta.url is `file:///C:/...`, so a hand-built `file://` + path never
// matches and the script silently does nothing.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { source, ids } = buildPrompts();
  writeFileSync(OUT, source);
  console.log(`Wrote ${OUT} — ${ids.length} prompts (${ids.join(", ")})`);
}
